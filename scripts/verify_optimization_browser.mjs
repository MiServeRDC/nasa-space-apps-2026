// Local integration checks. Requires a built server, npm dependencies and
// PLAYWRIGHT_MODULE pointing to playwright-core (no runtime app dependency).
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtemp,open,readFile,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {pathToFileURL,fileURLToPath} from 'node:url';
import net from 'node:net';

const root=resolve(fileURLToPath(new URL('..',import.meta.url)));
const artifacts=await mkdtemp(join(tmpdir(),'ares-browser-optimization-'));
const {chromium}=await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE));
const port=async()=>{const s=net.createServer();await new Promise(r=>s.listen(0,'127.0.0.1',r));const p=s.address().port;await new Promise(r=>s.close(r));return p;};
const backendPort=await port(),uiPort=await port();
const base=`http://127.0.0.1:${backendPort}`,ui=`http://127.0.0.1:${uiPort}`;
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
async function until(fn,timeout=15000) {const start=Date.now();while(Date.now()-start<timeout){try{const v=await fn();if(v)return v;}catch{}await sleep(50);}throw Error('Timed out waiting for local verification');}
const backendLog=await open(join(artifacts,'server.log'),'w'),viteLog=await open(join(artifacts,'vite.log'),'w');
const backend=spawn(join(root,'target/debug/ares-server-cli'),['--mode','ws-only','--bind',`127.0.0.1:${backendPort}`,'--data-dir',join(root,'data/bidmc'),'--storage-dir',join(artifacts,'store')],{cwd:root,stdio:['ignore',backendLog.fd,backendLog.fd]});
const backendExit=new Promise(r=>backend.once('exit',(code,signal)=>r({code,signal})));
const vite=spawn(process.execPath,[join(root,'ares-cockpit/node_modules/vite/bin/vite.js'),'--host','127.0.0.1','--port',String(uiPort)],{cwd:join(root,'ares-cockpit'),env:{...process.env,VITE_ARES_HTTP_URL:base},stdio:['ignore',viteLog.fd,viteLog.fd]});
let browser;
const timers=new Set();
try {
  await until(async()=>(await fetch(`${base}/api/storage-status`)).ok);
  await until(async()=>(await fetch(ui)).ok);
  browser=await chromium.launch({executablePath:process.env.BROWSER_PATH,headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  let socket,frame=await (await fetch(`${base}/api/snapshot`)).json();
  await page.routeWebSocket(`ws://127.0.0.1:${backendPort}/ws/telemetry`,ws=>{
    socket=ws;ws.send(JSON.stringify(frame));
    const timer=setInterval(()=>ws.send(JSON.stringify(frame)),50);
    timers.add(timer);ws.onClose(()=>{clearInterval(timer);timers.delete(timer);});
  });
  await page.goto(`${ui}/tests/telemetry-harness.html`);
  const state=async()=>JSON.parse(await page.locator('output').innerText());
  await until(async()=>(await state()).link==='ENGINE_LIVE');
  await sleep(100);const live=(await state()).localFrames;
  await sleep(350);assert.equal((await state()).localFrames,live,'unused fallback must stop during live telemetry');
  await page.getByRole('button',{name:'Toggle preview'}).click();
  await sleep(250);assert.ok((await state()).localFrames>live,'What-If preview must run when requested');
  await page.getByRole('button',{name:'Toggle preview'}).click();
  await sleep(100);const paused=(await state()).localFrames;
  frame={...frame,safety_margins:{...frame.safety_margins,alarm_level:'CRITICAL'}};
  await until(async()=>(await state()).alarm==='CRITICAL');
  assert.equal((await state()).localFrames,paused,'alarm delivery must not restart unused simulation');
  assert.equal((await state()).missing,true,'HRV missing values must survive transport');
  socket.close({code:1012,reason:'test reconnect'});
  await until(async()=>(await state()).link==='LOCAL_SIMULATION');
  await sleep(150);assert.ok((await state()).localFrames>paused);
  await until(async()=>(await state()).link==='ENGINE_LIVE',6000);
  console.log('Live/fallback/preview/alarm/reconnect hook checks passed.');

  const requests=[];page.on('request',r=>requests.push(r.url()));
  await page.goto(`${ui}/?phase=GATHER`);
  await page.getByRole('heading',{name:'Health overview',exact:true}).waitFor();
  assert.equal(requests.some(url=>url.includes('/body-3d-heatmap/BodyHeatmap.tsx')),false,'Overview must not fetch optional 3D');
  await page.getByRole('button',{name:'Ground portal',exact:true}).click();
  await until(()=>requests.some(url=>url.includes('/portal/MissionPortal.tsx')));
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:/Assessment/}).click();
  await page.getByLabel('Render quality',{exact:true}).selectOption('LITE');
  await page.getByRole('button',{name:/Overview/}).click();
  await page.getByRole('button',{name:/Assessment/}).click();
  assert.equal(await page.getByLabel('Render quality',{exact:true}).inputValue(),'LITE','manual quality should survive navigation');
  await page.locator('canvas').first().scrollIntoViewIfNeeded();
  await sleep(500);
  const density=await page.locator('canvas').first().evaluate(c=>({width:c.width,cssWidth:c.getBoundingClientRect().width}));
  assert.ok(density.width<=Math.ceil(density.cssWidth*0.76),'Lite must cap pixel density');
  await page.getByRole('button',{name:'Ground portal',exact:true}).click();
  await until(async()=>await page.locator('[data-render-loop]').first().getAttribute('data-render-loop')==='never');
  await page.keyboard.press('Escape');
  await page.getByLabel('Render quality',{exact:true}).selectOption('HIGH');
  await page.emulateMedia({reducedMotion:'reduce'});
  await until(async()=>await page.locator('[data-render-loop]').getAttribute('data-render-loop')==='demand');
  await page.evaluate(()=>{Object.defineProperty(document,'hidden',{value:true,configurable:true});document.dispatchEvent(new Event('visibilitychange'));});
  await until(async()=>await page.locator('[data-render-loop]').getAttribute('data-render-loop')==='never');
  await page.evaluate(()=>{delete document.hidden;document.dispatchEvent(new Event('visibilitychange'));});
  await page.getByLabel('Render quality',{exact:true}).selectOption('LITE');
  await page.screenshot({path:join(artifacts,'desktop.png')});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:join(artifacts,'mobile.png'),fullPage:true});
  assert.deepEqual(errors,[]);
  const failedPanel=await browser.newPage();
  await failedPanel.route('**/src/modules/portal/MissionPortal.tsx*',route=>route.abort());
  await failedPanel.goto(`${ui}/?phase=GATHER`);
  await failedPanel.getByRole('button',{name:'Ground portal',exact:true}).click();
  await failedPanel.getByRole('alert').filter({hasText:'ground portal could not be loaded'}).waitFor();
  assert.equal(await failedPanel.getByRole('heading',{name:'Health overview',exact:true}).count(),1,'a failed optional chunk must not unmount the monitor');
  await failedPanel.close();
  const heldConnection=await browser.newPage();
  await heldConnection.goto(`${ui}/?phase=GATHER`);
  await heldConnection.getByText('Engine connected',{exact:true}).waitFor();
  const status=await (await fetch(`${base}/api/storage-status`)).json();
  assert.ok(status.status.total_pushed_frames>0);
  backend.kill('SIGINT');
  const exit=await Promise.race([backendExit,sleep(10000).then(()=>{throw Error('server shutdown did not drain');})]);
  assert.equal(exit.code,0);
  await browser.close();browser=null;
  const manifest=JSON.parse(await readFile(join(artifacts,'store/MANIFEST.lsah.json'),'utf8'));
  const rows=manifest.payload.segments.reduce((sum,s)=>sum+s.row_count,0);
  assert.ok(rows>=status.status.total_pushed_frames,'SIGINT must persist the final partial batch');
  await writeFile(join(artifacts,'results.json'),JSON.stringify({hookChecks:'passed',pageErrors:errors,recordedRows:rows,storageBeforeShutdown:status.status,liveFallbackFrames:live,density},null,2));
  console.log(`UI/lazy-loading/Lite/mobile/storage-shutdown checks passed. Artifacts: ${artifacts}`);
} finally {
  for(const timer of timers) clearInterval(timer);
  if(browser) await browser.close();
  if(backend.exitCode===null) backend.kill('SIGTERM');
  vite.kill('SIGTERM');await backendLog.close();await viteLog.close();
}
