/** Compare normalized, acyclic telemetry values without allocating JSON strings.
 * Used only at expensive rendering boundaries, never to throttle alarm delivery.
 */
export function equalTelemetryValue(a: unknown, b: unknown): boolean {
  if (Object.is(a, b)) return true;
  if (a === null || b === null || typeof a !== 'object' || typeof b !== 'object') return false;
  if (Array.isArray(a) !== Array.isArray(b)) return false;
  const left = a as Record<string, unknown>;
  const right = b as Record<string, unknown>;
  const keys = Object.keys(left);
  return keys.length === Object.keys(right).length && keys.every(key =>
    Object.prototype.hasOwnProperty.call(right, key) && equalTelemetryValue(left[key], right[key]));
}
